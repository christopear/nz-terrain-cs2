"""Experimental broad-bottom Hollyford beds; does not change package defaults.

Run: uv run --all-packages python packages/water-carver/examples/plot_broad_beds.py
The eased shelf is a plotting experiment using exact distances generated by the
carver. It is not yet a supported production profile.
"""
import json
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from pyproj import Transformer
from shapely.affinity import translate
from shapely.geometry import shape
from shapely.ops import transform, unary_union
from scipy.ndimage import map_coordinates
from water_carver import Bed, BedParameters, generate_bed
from plot_samples import ROOT, grid_for

OUT=ROOT/'output/water-carver-samples/hollyford-broad-beds'
OUT.mkdir(parents=True,exist_ok=True)
source=ROOT/'river-configs/jamestown-hollyford-polygons.geojson'
project=Transformer.from_crs(4326,2193,always_xy=True).transform
water=unary_union([transform(project,shape(f['geometry'])) for f in json.loads(source.read_text())['features']])
x0,y0,_,_=water.bounds;water=translate(water,-x0,-y0)
_,_,x1,y1=water.bounds;spacing=2
grid=grid_for((-30,-30,x1+30,y1+30),spacing)
# Linear depth with unit slope equals bank distance until its cap. Set the cap
# beyond the whole polygon bounding-box diagonal, so it cannot affect results.
distance_bed=generate_bed(water,grid,water_level_m=0,parameters=BedParameters(np.hypot(x1,y1)+100,1,'linear'))
distance=distance_bed.depth_m
variants=[
    dict(key='baseline',title='Previous tanh · 10 m / 10%',cap=10,kind='tanh',gradient=.1,color='#7a7f86'),
    dict(key='steep_tanh',title='Steeper tanh · 10 m / 30%',cap=10,kind='tanh',gradient=.3,color='#2b78b7'),
    dict(key='trapezoid',title='Straight bank · 10 m / 50%',cap=10,kind='linear',gradient=.5,color='#b15c24'),
    dict(key='shelf40',title='Rounded shelf · 10 m / 40 m bank run',cap=10,kind='shelf',run=40,color='#7a52a4'),
    dict(key='shelf20',title='Rounded shelf · 10 m / 20 m bank run',cap=10,kind='shelf',run=20,color='#008778'),
    dict(key='shelf6',title='Rounded shelf · 6 m / 20 m bank run',cap=6,kind='shelf',run=20,color='#c34a72'),
]

def depths(v,d):
    if v['kind']!='shelf':
        return BedParameters(v['cap'],v['gradient'],v['kind']).depths(d)
    u=np.clip(d/v['run'],0,1)
    return v['cap']*u*u*(3-2*u)

beds={};stats=[]
for v in variants:
    z=np.full(grid.shape,np.nan);z[distance_bed.mask]=depths(v,distance[distance_bed.mask])
    beds[v['key']]=Bed(grid,distance_bed.mask,z,-z)
    stats.append(dict(**v,deepest_m=float(np.nanmax(z)),mean_m=float(np.nanmean(z)),water_area_at_least_90percent_depth_pct=float(np.mean(z[distance_bed.mask]>=v['cap']*.9)*100),maximum_bank_slope_percent=(1.5*v['cap']/v['run']*100 if v['kind']=='shelf' else v['gradient']*100)))

def plan(ax,bed):
    a=grid.transform;h,w=grid.shape
    return ax.imshow(bed.depth_m,origin='upper',extent=(a.c,a.c+spacing*w,a.f-spacing*h,a.f),vmin=0,vmax=10,cmap='YlGnBu',interpolation='nearest')

# Profiles first: ideal cross section deliberately makes the flat floor obvious.
fig,axes=plt.subplots(1,3,figsize=(17,6),layout='constrained')
d=np.linspace(0,160,1001)
for v in variants:
    axes[0].plot(d,-depths(v,d),label=v['title'],color=v['color'],lw=2)
for ax,width in zip(axes[1:],[200,60]):
    x=np.linspace(0,width,1001);nearest=np.minimum(x,width-x)
    for v in variants:ax.plot(x,-depths(v,nearest),color=v['color'],lw=2)
    ax.set(title=f'Ideal {width} m-wide channel',xlabel='Across channel (m)')
axes[0].set(title='From one bank inward',xlabel='Nearest-bank distance (m)')
for ax in axes:
    ax.set(ylabel='Bed relative to water surface (m)',ylim=(-11,.5));ax.grid(alpha=.2);ax.axhline(0,ls='--',color='#77838a',lw=1)
handles,labels=axes[0].get_legend_handles_labels()
fig.legend(handles,labels,loc='outside lower center',ncol=2,fontsize=10)
fig.suptitle('Broad-bed experiments / steep sides, deeper usable floor\nRounded shelf reaches its full depth at the stated bank run, then remains flat',fontsize=17)
fig.savefig(OUT/'01-shape-comparisons.png',dpi=170);plt.close(fig)

fig,axes=plt.subplots(2,3,figsize=(12,17),layout='constrained',sharex=True,sharey=True)
for ax,v,s in zip(axes.flat,variants,stats):
    im=plan(ax,beds[v['key']]);ax.set_title(v['title']+f"\n{s['water_area_at_least_90percent_depth_pct']:.0f}% of water area ≥90% target depth",fontsize=10)
    ax.set(xlabel='Local easting (m)',ylabel='Local northing (m)')
fig.colorbar(im,ax=axes.ravel().tolist(),shrink=.45,label='Synthetic depth (m) · shared scale')
fig.suptitle('Hollyford / broad-bottom alternatives\nActual polygon · 2 m grid · flat reference water level 0 m',fontsize=17)
fig.text(.5,.004,'LINZ geometry: CC BY 4.0. No terrain or flow simulation. River-end closures still count as banks.',ha='center',fontsize=9)
fig.set_constrained_layout_pads(h_pad=.4,w_pad=.1)
fig.savefig(OUT/'02-polygon-comparisons.png',dpi=170);plt.close(fig)

sections=[('Broad northern reach',4850),('Island reach',4000),('Narrower southern reach',1250)]
fig,axes=plt.subplots(3,3,figsize=(17,12),layout='constrained',width_ratios=[.6,1.4,1.4])
x=np.arange(-20,x1+20,1.)
for row,(label,y) in enumerate(sections):
    im=plan(axes[row,0],beds['shelf20']);axes[row,0].axhline(y,color='#ba4946',ls='--',lw=1.3)
    axes[row,0].set(title=label,xlabel='Easting (m)',ylabel='Northing (m)')
    coords=[np.full_like(x,(grid.transform.f-y)/spacing-.5),(x-grid.transform.c)/spacing-.5]
    mask=map_coordinates(distance_bed.mask.astype(float),coords,order=0,mode='constant',cval=0)>0
    valid=x[mask]
    for ax,selection,title in [(axes[row,1],variants[:3],'Tanh versus straight, steep banks'),(axes[row,2],[variants[0],*variants[3:]],'Rounded shelf: bank run and depth')]:
        for v in selection:
            values=map_coordinates(beds[v['key']].elevation_m,coords,order=1,mode='constant',cval=np.nan)
            ax.plot(x,values,color=v['color'],lw=2,label=v['title'])
        ax.set(title=title,xlabel='Local easting (m)',ylabel='Bed elevation (m)',ylim=(-11,.5),xlim=(valid.min()-15,valid.max()+15));ax.grid(alpha=.2)
        ax.axhline(0,color='#77838a',ls='--',lw=1)
        if row==0:ax.legend(fontsize=8,loc='lower center')
fig.suptitle('Actual Hollyford sections / broad beds without widening the polygon\nEast–west cuts; gaps remain land or islands',fontsize=18)
fig.savefig(OUT/'03-actual-cross-sections.png',dpi=170);plt.close(fig)
(OUT/'parameters.json').write_text(json.dumps(dict(experimental=True,reference_level_m=0,grid_spacing_m=spacing,variants=stats,shelf_formula='depth = D * (3u^2 - 2u^3), u = clip(bank_distance / bank_run, 0, 1)'),indent=2)+'\n')
(OUT/'README.md').write_text('''# Hollyford: broader, deeper beds

Six experiments using the same polygon. No existing terrain, production defaults or carver behaviour has been changed. Flat reference surface at 0 m, 2 m raster; all polygon edges including end closures still count as banks. Not a game water-flow test.

## Shapes and ideal channels

![Shapes](01-shape-comparisons.png)

## Actual Hollyford sections

![Sections](03-actual-cross-sections.png)

## Polygon depths

![Polygon depths](02-polygon-comparisons.png)

The experimental rounded shelf uses `depth = D * (3u² - 2u³)`, where `u = min(distance_to_bank / bank_run, 1)`. It starts and finishes with zero slope, reaches the target depth at the bank run, and is flat thereafter. Bank run is horizontal distance per side, not total channel width. Peak slopes are 37.5% (10 m / 40 m), 75% (10 m / 20 m), and 45% (6 m / 20 m); these are percentages, not degrees.

For the 10 m / 20 m shelf, a straight 200 m channel gets approximately 160 m of flat floor; a 60 m channel gets 20 m. Channels narrower than 40 m cannot attain full depth, and can still have a central crease. Distance-to-bank geometry can still produce uneven longitudinal beds. Shoreline positions and islands are preserved.

The original tanh and linear profiles are supported by the package. Rounded shelves are isolated experiments here, pending review. The 6 m alternative demonstrates a broad floor without requiring 10 m everywhere. The colour scale is shared across every polygon panel. “≥90% target depth” is a per-variant area fraction, not a common absolute depth threshold.
''')
print(json.dumps(stats,indent=2))
